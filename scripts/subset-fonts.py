"""Subset Inclusive Sans into a preloaded core file and an on-demand extended file.

Run by hand from the repo root, then commit the output:

    uv run scripts/subset-fonts.py

Rerun when content starts using a character outside ASCII, Latin-1 and
Latin Extended-A (the script scans src/ and adds any such character the font
has), when the site starts using another weight, style or OpenType feature of
Inclusive Sans, or to move to a newer upstream font (update SOURCE_URL and
SOURCE_SHA256).
"""

import hashlib
import io
import pathlib
import subprocess
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src/assets/fonts"
CSS = ROOT / "src/styles/fonts.css"
SOURCE_URL = "https://raw.githubusercontent.com/google/fonts/6157dfaa640ca5738b4d1a7070fe389c3036d7fc/ofl/inclusivesans/InclusiveSans%5Bwght%5D.ttf"
SOURCE_SHA256 = "52ae5fdb8eda45633f1e9817ebdb07d8075c89081d51204f16f78394608a5c4e"

# The site only declares weight 400; 500-700 and italic are synthesized by the
# browser from it, so the instance stays static at 400 to render identically.
WGHT = 400
# Default-on features the site's text exercises. mark/ccmp only act on
# combining marks, which no content uses; locl has no en/pt-BR entries.
FEATURES = ["kern"]

ASCII = set(range(0x20, 0x7F))
PUNCTUATION = {ord(c) for c in "‘’“”–—…"}
# Portuguese accents: half the site is pt-BR and English pages use them too.
PORTUGUESE = {ord(c) for c in "ÁÀÂÃÇÉÊÍÓÔÕÚáàâãçéêíóôõú"}
CORE = ASCII | PUNCTUATION | PORTUGUESE
LATIN = set(range(0xA0, 0x100)) | set(range(0x100, 0x180))


def used_codepoints():
    exts = {".astro", ".svelte", ".tsx", ".ts", ".md", ".mdx", ".css", ".json"}
    return {
        ord(c)
        for p in (ROOT / "src").rglob("*")
        if p.suffix in exts
        for c in p.read_text(encoding="utf-8")
    }


def unicode_range(codepoints):
    cps, ranges = sorted(codepoints), []
    for cp in cps:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def build(source, codepoints, stem):
    options = subset.Options()
    options.layout_features = FEATURES
    options.hinting = False
    options.drop_tables += ["gasp", "STAT", "DSIG"]
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]  # keep copyright + OFL notice
    font = TTFont(io.BytesIO(source), recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    contained = set(font.getBestCmap())
    font.flavor = "woff2"  # Options.flavor only applies to subset.save_font
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()
    name = f"{stem}.woff2"
    (OUT_DIR / name).write_bytes(data)
    print(f"{name}: {len(data)} B, {font['maxp'].numGlyphs} glyphs, {len(contained)} chars")
    return name, contained


raw = urllib.request.urlopen(SOURCE_URL).read()
digest = hashlib.sha256(raw).hexdigest()
assert digest == SOURCE_SHA256, f"source changed: {digest}"
font = instancer.instantiateVariableFont(TTFont(io.BytesIO(raw), recalcTimestamp=False), {"wght": WGHT})
# The fontsource build had no overlap flags. Skia antialiases flagged glyphs
# differently (visible on the diaeresis of Ÿ), so clear them to match.
glyf = font["glyf"]
for name in font.getGlyphOrder():
    glyph = glyf[name]
    if glyph.isComposite():
        for component in glyph.components:
            component.flags &= ~0x400  # OVERLAP_COMPOUND
    elif glyph.numberOfContours > 0:
        glyph.expand(glyf)
        glyph.flags[0] &= ~0x40  # OVERLAP_SIMPLE
buf = io.BytesIO()
font.save(buf)
static = buf.getvalue()
# Arrows were never in the fontsource build the site shipped before, so they
# render in a system font. Keep it that way.
available = set(font.getBestCmap()) - set(range(0x2190, 0x2200))

OUT_DIR.mkdir(parents=True, exist_ok=True)
core_file, core = build(static, CORE & available, "inclusive-sans-core")
ext_file, ext = build(static, ((LATIN | used_codepoints()) & available) - core, "inclusive-sans-ext")
assert not core & ext

face = """@font-face {{
  font-family: "Inclusive Sans";
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url("../assets/fonts/{file}?no-inline") format("woff2");
  unicode-range: {range};
}}
"""
CSS.write_text(
    "/* Generated by scripts/subset-fonts.py. Do not edit. */\n"
    + face.format(file=core_file, range=unicode_range(core))
    + "\n"
    + face.format(file=ext_file, range=unicode_range(ext))
)
subprocess.run(["bunx", "vp", "fmt", str(CSS)], cwd=ROOT, check=True)
print(f"wrote {CSS.relative_to(ROOT)}")
